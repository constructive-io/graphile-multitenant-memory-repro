import assert from 'node:assert/strict';
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { projectPath } from '../paths.js';
import type { WorkerResult } from '../benchmark/results.js';
import { scenarioOrder, scenarios } from '../benchmark/scenarios.js';
import { readSample, readVerification, readAnalysis } from './read.js';

const median = (values: number[]) => {
  const sorted = [...values].sort((a, b) => a - b);
  assert(sorted.length > 0);
  const middle = Math.floor(sorted.length / 2);
  return sorted.length % 2
    ? sorted[middle]
    : (sorted[middle - 1] + sorted[middle]) / 2;
};
function metrics(row: WorkerResult): Record<string, number> {
  const result: Record<string, number> = {
    heapMiB: row.retained.heapUsed / 2 ** 20,
    baselineMiB: row.baseline.heapUsed / 2 ** 20,
    rssMiB: row.retained.rss / 2 ** 20,
    forcedGcMs: median(row.retained.gcPausesMs),
  };
  if (row.scenario !== 'd')
    result.afterReleaseMiB = row.afterRelease.heapUsed / 2 ** 20;
  if ('heapDelta' in row) result.incrementMiB = row.heapDelta / 2 ** 20;
  if ('buildMs' in row) result.buildMs = row.buildMs;
  if (row.scenario === 'b')
    result.perInstanceMiB = row.heapPerInstance / 2 ** 20;
  if (row.scenario === 'c') result.perOperationKiB = row.heapPerPlan / 1024;
  if (row.scenario === 'rotation') {
    for (const round of row.rounds)
      result[`round${round.round}MiB`] = round.memory.heapUsed / 2 ** 20;
    result.lastMinusThirdMiB =
      (row.rounds[4].memory.heapUsed - row.rounds[2].memory.heapUsed) / 2 ** 20;
  }
  return result;
}
function readRun(name: string) {
  const dir = projectPath('results', name);
  const verification = readVerification(`${dir}/verification.json`);
  assert.equal(verification.status, 'passed');
  assert.equal(verification.workers, 42);
  const samples = readdirSync(dir)
    .filter((file) => /^(a|b|c|d|rotation)-\d+-r\d+\.json$/.test(file))
    .map((file) => readSample(`${dir}/${file}`));
  assert.equal(samples.length, 42);
  return { name, dir, verification, samples };
}
export function compareRefactor(
  names: string[],
  outputDirectory: string,
): void {
  assert.equal(
    names.length,
    4,
    'Pass old base, new base, old PR2, new PR2 and an output directory',
  );
  const runs = names.map(readRun);
  const pairs = [
    { profile: 'common-base', before: runs[0], after: runs[1] },
    { profile: 'pr2', before: runs[2], after: runs[3] },
  ];
  const deltas = pairs.flatMap(({ profile, before, after }) => {
    assert.equal(before.verification.comparisonProfile, profile);
    assert.equal(after.verification.comparisonProfile, profile);
    assert.equal(
      before.verification.crystal?.sha,
      after.verification.crystal?.sha,
    );
    assert.deepEqual(
      before.verification.dependencies,
      after.verification.dependencies,
    );
    assert.equal(before.verification.sdlHash, after.verification.sdlHash);
    return scenarioOrder.flatMap((scenario) =>
      scenarios[scenario].points.flatMap((value) => {
        const oldRows = before.samples
          .filter((row) => row.scenario === scenario && row.value === value)
          .map(metrics);
        const newRows = after.samples
          .filter((row) => row.scenario === scenario && row.value === value)
          .map(metrics);
        assert.equal(oldRows.length, 3);
        assert.equal(newRows.length, 3);
        return Object.keys(oldRows[0]).map((metric) => {
          const previous = median(oldRows.map((row) => row[metric]));
          const current = median(newRows.map((row) => row[metric]));
          return {
            profile,
            scenario,
            value,
            metric,
            previous,
            current,
            delta: current - previous,
            percent:
              previous === 0 ? null : (100 * (current - previous)) / previous,
          };
        });
      }),
    );
  });
  mkdirSync(outputDirectory, { recursive: true });
  const lines = [
    '# TypeScript refactor: fresh versus historical measurements',
    '',
    'Each new group contains the complete existing 42-worker matrix, including five-pass rotation and six separately analyzed snapshots. All points have three independent processes. Historical files retain their original source commits; they were not generated by the TypeScript implementation.',
    '',
    'The comparisons below hold the pinned Crystal SHA and runtime dependency versions fixed within each profile. They compare different harness sources and execution times/environments, so timing/RSS/GC differences are descriptive and do not isolate a compiler effect. See the validation narrative for investigation of material deviations.',
    '',
    '## Run identity',
    '',
    '| Profile | Generation | Harness SHA | Build/compiler | Full report |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const pair of pairs)
    for (const [generation, run] of [
      ['historical', pair.before],
      ['refactored', pair.after],
    ] as const) {
      lines.push(
        `| ${pair.profile} | ${generation} | ${run.verification.sourceSha} | ${run.samples[0].environment.build?.compiler ?? 'original JavaScript'} | [Report](${relative(outputDirectory, `${run.dir}/REPORT.md`)}) |`,
      );
    }
  lines.push(
    '',
    '## Environment',
    '',
    '| Profile | Field | Historical | Refactored |',
    '| --- | --- | --- | --- |',
  );
  for (const pair of pairs) {
    const before = pair.before.samples[0].environment,
      after = pair.after.samples[0].environment;
    for (const key of [
      'node',
      'v8',
      'postgres',
      'platform',
      'arch',
      'cpuModel',
      'cpus',
      'totalMemory',
      'quietMs',
      'gcPasses',
    ] as const)
      lines.push(
        `| ${pair.profile} | ${key} | ${before[key]} | ${after[key]} |`,
      );
    assert.deepEqual(before.postgresSettings, after.postgresSettings);
  }
  lines.push(
    '',
    'SDL hashes, runtime dependency versions and PostgreSQL settings match within each old/new profile pair. The matrix and controlled-comparison verifiers also check RLS-tested preflight provenance, plan counts/replay, build/release accounting and the complete matrix. New worker records include PIDs, exact Node arguments and compiled-output hashes.',
    '',
    '## Primary measurements',
    '',
    '| Profile | Point | Metric | Historical | Refactored | Delta | Change |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  );
  const primary = deltas.filter((row) =>
    [
      'heapMiB',
      'buildMs',
      'perOperationKiB',
      'perInstanceMiB',
      'lastMinusThirdMiB',
    ].includes(row.metric),
  );
  for (const row of primary)
    lines.push(
      `| ${row.profile} | ${row.scenario}-${row.value} | ${row.metric} | ${row.previous.toFixed(2)} | ${row.current.toFixed(2)} | ${row.delta.toFixed(2)} | ${row.percent?.toFixed(2) ?? 'n/a'}% |`,
    );
  lines.push(
    '',
    '## Rotation trajectory',
    '',
    '| Profile | Metric | Historical MiB | Refactored MiB | Delta MiB |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const row of deltas.filter((row) => /^round\dMiB$/.test(row.metric)))
    lines.push(
      `| ${row.profile} | ${row.metric} | ${row.previous.toFixed(2)} | ${row.current.toFixed(2)} | ${row.delta.toFixed(2)} |`,
    );
  lines.push(
    '',
    '## N=150 snapshot signatures',
    '',
    '| Profile | Signature | Historical / refactored count | Historical / refactored retained MiB |',
    '| --- | --- | --- | --- |',
  );
  for (const pair of pairs) {
    const analyses = [pair.before, pair.after].map((run) =>
      [1, 2, 3].map((repeat) =>
        readAnalysis(`${run.dir}/d-150-r${repeat}.json.analysis.json`),
      ),
    );
    const labels = new Set(
      analyses.flatMap((rows) =>
        rows.flatMap((row) =>
          row.signatures.map((signature) => signature.label),
        ),
      ),
    );
    for (const label of labels) {
      const counts = analyses.map((rows) =>
        median(
          rows.map(
            (row) => row.signatures.find((s) => s.label === label)?.count ?? 0,
          ),
        ),
      );
      const retained = analyses.map(
        (rows) =>
          median(
            rows.map(
              (row) =>
                row.signatures.find((s) => s.label === label)
                  ?.unionRetainedBytes ?? 0,
            ),
          ) /
          2 ** 20,
      );
      lines.push(
        `| ${pair.profile} | ${label} | ${counts.join(' / ')} | ${retained.map((value) => value.toFixed(2)).join(' / ')} |`,
      );
    }
  }
  lines.push(
    '',
    'Signature categories overlap and must not be summed. D release measurements are snapshot-perturbed and excluded from ordinary release comparisons. All metric deltas, including RSS, baseline, release and explicit GC pauses, are in [refactor-deltas.json](./refactor-deltas.json). No plan-memory branch was added.',
    '',
  );
  writeFileSync(
    resolve(outputDirectory, 'REFACTOR-COMPARISON.md'),
    lines.join('\n'),
  );
  writeFileSync(
    resolve(outputDirectory, 'refactor-deltas.json'),
    JSON.stringify(
      {
        runs: runs.map((run) => ({
          name: run.name,
          sourceSha: run.verification.sourceSha,
          environment: run.samples[0].environment,
        })),
        deltas,
      },
      null,
      2,
    ) + '\n',
  );
}
